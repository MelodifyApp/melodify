"use strict";

/**
 * Generates THIRD-PARTY-NOTICES.md from the production dependency tree.
 * Electron's LICENSE and LICENSES.chromium.html ship next to the executable.
 */

const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const brand = JSON.parse(
    fs.readFileSync(path.join(root, "src", "shared", "brand.json"), "utf8")
);
const packageJson = JSON.parse(
    fs.readFileSync(path.join(root, "package.json"), "utf8")
);
const lock = JSON.parse(
    fs.readFileSync(path.join(root, "package-lock.json"), "utf8")
);

function licenseOf(value) {
    if (typeof value === "string" && value.trim()) return value.trim();
    if (value && typeof value === "object" && typeof value.type === "string") {
        return value.type;
    }
    return "SEE PACKAGE";
}

function repositoryOf(value) {
    if (typeof value === "string") return value;
    if (value && typeof value === "object" && typeof value.url === "string") {
        return value.url.replace(/^git\+/, "").replace(/\.git$/, "");
    }
    return "";
}

const rows = [];
for (const [packagePath, entry] of Object.entries(lock.packages || {})) {
    if (!packagePath || entry.dev === true || entry.link === true) continue;
    const manifestPath = path.join(root, packagePath, "package.json");
    if (!fs.existsSync(manifestPath)) continue;
    let manifest;
    try {
        manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
    } catch {
        continue;
    }
    if (!manifest.name || !manifest.version) continue;
    rows.push({
        name: manifest.name,
        version: manifest.version,
        license: licenseOf(manifest.license),
        repository: repositoryOf(manifest.repository),
    });
}

rows.sort((a, b) =>
    `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`)
);

const lines = [
    "# Third-party notices",
    "",
    `${brand.displayName} ${packageJson.version} is distributed under the MIT License.`,
    "Copyright (c) 2025 emirhanpisgin.",
    "",
    "This application includes Electron and Chromium. Their license texts ship",
    "next to the application executable as `LICENSE` and",
    "`LICENSES.chromium.html`.",
    "",
    "The production npm packages listed below are included in or used by the",
    "application. Full license texts are available from each package or its",
    "repository; where a package ships a LICENSE file, that file is the",
    "authoritative text.",
    "",
    "| Package | Version | License | Repository |",
    "| --- | --- | --- | --- |",
];

for (const row of rows) {
    const repository = row.repository
        ? `[${row.repository}](${row.repository})`
        : "";
    lines.push(
        `| \`${row.name}\` | ${row.version} | ${row.license} | ${repository} |`
    );
}

lines.push(
    "",
    "This notice is generated by `scripts/generate-third-party-notices.cjs`.",
    "Do not edit it by hand.",
    ""
);

fs.writeFileSync(
    path.join(root, "THIRD-PARTY-NOTICES.md"),
    lines.join("\n"),
    "utf8"
);
console.log(`THIRD_PARTY_NOTICES_GENERATED packages=${rows.length}`);
